#!/bin/bash
# script-gen.sh - Interactive generator for new Bash scripts
# Usage: ./script-gen.sh [output_dir]   (default: ./scripts)

set -u

OUT_DIR="${1:-./scripts}"
mkdir -p "$OUT_DIR"

# --- Gather input -----------------------------------------------------------
read -rp "Script name (without .sh): " name
name="${name// /-}"
if [[ ! "$name" =~ ^[A-Za-z0-9_-]+$ ]]; then
    echo "Invalid name. Use letters, numbers, - and _ only." >&2
    exit 1
fi

file="$OUT_DIR/$name.sh"
if [ -e "$file" ]; then
    read -rp "$file already exists. Overwrite? [y/N]: " ow
    [[ "$ow" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 1; }
fi

read -rp "One-line description: " desc
read -rp "Require root? [y/N]: " need_root

echo
echo "Choose what the script should do:"
echo "  1) Disk usage report with threshold warning"
echo "  2) Check if a service is running (systemctl)"
echo "  3) Back up a directory to a .tar.gz"
echo "  4) Custom (type your own commands)"
read -rp "Choice [1-4]: " choice

case "$choice" in
    1) usage="[threshold_percent]" ;;
    2) usage="<service_name>" ;;
    3) usage="<source_dir> [backup_dir]" ;;
    4) usage="" ;;
    *) echo "Invalid choice." >&2; exit 1 ;;
esac

# --- Write header -----------------------------------------------------------
cat > "$file" <<EOF
#!/bin/bash
# $name.sh - $desc
# Generated by script-gen.sh on $(date '+%F')
# Usage: ./$name.sh $usage

set -euo pipefail

EOF

if [[ "$need_root" =~ ^[Yy]$ ]]; then
    cat >> "$file" <<'EOF'
if [ "$EUID" -ne 0 ]; then
    echo "Please run as root (or with sudo)." >&2
    exit 1
fi

EOF
fi

# --- Write body -------------------------------------------------------------
case "$choice" in
    1)
        cat >> "$file" <<'EOF'
THRESHOLD="${1:-80}"

df -hT -x tmpfs -x devtmpfs
echo

df -P -x tmpfs -x devtmpfs | awk 'NR>1 {print $1, $5, $6}' | while read -r fs pct mount; do
    pct="${pct%\%}"
    if [ "$pct" -ge "$THRESHOLD" ]; then
        echo "WARNING: $mount ($fs) is ${pct}% full"
    fi
done
EOF
        ;;
    2)
        cat >> "$file" <<'EOF'
SERVICE="${1:?Usage: $0 <service_name>}"

if systemctl is-active --quiet "$SERVICE"; then
    echo "$SERVICE is running."
else
    echo "$SERVICE is NOT running." >&2
    systemctl status "$SERVICE" --no-pager | head -n 10
    exit 1
fi
EOF
        ;;
    3)
        cat >> "$file" <<'EOF'
SRC="${1:?Usage: $0 <source_dir> [backup_dir]}"
DEST="${2:-/backup}"
STAMP="$(date '+%F_%H%M%S')"
ARCHIVE="$DEST/$(basename "$SRC")-$STAMP.tar.gz"

[ -d "$SRC" ] || { echo "Source directory not found: $SRC" >&2; exit 1; }
mkdir -p "$DEST"

tar -czf "$ARCHIVE" -C "$(dirname "$SRC")" "$(basename "$SRC")"
echo "Backup created: $ARCHIVE ($(du -h "$ARCHIVE" | cut -f1))"
EOF
        ;;
    4)
        echo
        echo "Type your commands one per line. Press Enter on an empty line to finish."
        while true; do
            read -rp "cmd> " line
            [ -z "$line" ] && break
            echo "$line" >> "$file"
        done
        ;;
esac

# --- Finish -----------------------------------------------------------------
chmod +x "$file"
echo
echo "Created: $file"

if bash -n "$file"; then
    echo "Syntax check: OK"
else
    echo "Syntax check: FAILED - open the file and fix it" >&2
fi
